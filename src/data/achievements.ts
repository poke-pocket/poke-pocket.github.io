import type { GameSave, GrowthStage, IvRank, PetIVs, SpeciesId } from '../types/pet';

export type AchievementCategory = 'care' | 'dex' | 'battle' | 'collect' | 'legend';

export interface AchievementEvalContext {
  save: GameSave;
  discovered: Set<SpeciesId>;
  totalSpeciesCount: number;
  hasAllSpecies: (ids: SpeciesId[]) => boolean;
  countDiscoveredByElement: (el: string) => number;
  totalFeeds: number;
  totalCleanOrBath: number;
  totalPats: number;
  teenOrHigherCount: number;
  adultStageCount: number;
  maxPetLevel: number;
  lv30Count: number;
  lv50Count: number;
  maxHappiness: number;
  ownedAccessories: number;
  ownedRooms: number;
  totalOwnedCosmetics: number;
  totalLabLevels: number;
  totalHeroSkillLevels: number;
  bestCoins: number;
  sRankCount: number;
  ssRankCount: number;
  aRankOrHigherCount: number;
  unlockedCount: number;
}

export interface AchievementMeta {
  id: string;
  title: string;
  description: string;
  rewardCoins: number;
  badge: string;
  category: AchievementCategory;
  isMeta?: boolean;
  check: (ctx: AchievementEvalContext) => boolean;
}

export function buildAchievementContext(
  save: GameSave,
  helpers: {
    getPetIVs: (pet: GameSave['pets'][number]) => PetIVs;
    getIvRank: (ivs: PetIVs) => IvRank;
    getGrowthStage: (level: number, species?: SpeciesId) => GrowthStage;
    getElement: (species: SpeciesId) => string | undefined;
    totalSpeciesCount: number;
  },
  unlockedCount: number,
): AchievementEvalContext {
  const discovered = new Set(save.discoveredSpecies);
  const ownedAccessories = save.unlockedAccessories.filter((a) => a !== 'none').length;
  const ownedRooms = save.unlockedRooms.filter((r) => r !== 'pokeball_room').length;
  const totalFeeds = save.pets.reduce((s, p) => s + p.totalFeeds, 0);
  const totalCleanOrBath = save.pets.reduce((s, p) => s + p.totalBaths + p.totalCleans, 0);
  const totalPats = save.pets.reduce((s, p) => s + p.totalPats, 0);
  const teenOrHigherCount = save.pets.filter((p) => helpers.getGrowthStage(p.level, p.species) !== 'baby').length;
  const adultStageCount = save.pets.filter((p) => helpers.getGrowthStage(p.level, p.species) === 'adult').length;
  const maxPetLevel = save.pets.reduce((mx, p) => Math.max(mx, p.level), 0);
  const lv30Count = save.pets.filter((p) => p.level >= 30).length;
  const lv50Count = save.pets.filter((p) => p.level >= 50).length;
  const maxHappiness = save.pets.reduce((mx, p) => Math.max(mx, p.happiness), 0);
  const meta = save.meta;
  const totalLabLevels = meta?.labLevels
    ? Object.values(meta.labLevels).reduce((s, v) => s + (v ?? 0), 0)
    : 0;
  const totalHeroSkillLevels = meta?.heroSkillLevels
    ? Object.values(meta.heroSkillLevels).reduce((s, v) => s + (v ?? 0), 0)
    : 0;
  const bestCoins = Math.max(save.coins, meta?.totalCoinsEarned ?? 0);

  let sRankCount = 0;
  let ssRankCount = 0;
  let aRankOrHigherCount = 0;
  for (const p of save.pets) {
    const r = helpers.getIvRank(helpers.getPetIVs(p));
    if (r === 'SS') {
      ssRankCount++;
      sRankCount++;
      aRankOrHigherCount++;
    } else if (r === 'S') {
      sRankCount++;
      aRankOrHigherCount++;
    } else if (r === 'A') {
      aRankOrHigherCount++;
    }
  }

  return {
    save,
    discovered,
    totalSpeciesCount: helpers.totalSpeciesCount,
    hasAllSpecies: (ids) => ids.every((sp) => discovered.has(sp)),
    countDiscoveredByElement: (el) => {
      let n = 0;
      for (const sp of discovered) {
        if (helpers.getElement(sp) === el) n++;
      }
      return n;
    },
    totalFeeds,
    totalCleanOrBath,
    totalPats,
    teenOrHigherCount,
    adultStageCount,
    maxPetLevel,
    lv30Count,
    lv50Count,
    maxHappiness,
    ownedAccessories,
    ownedRooms,
    totalOwnedCosmetics: ownedAccessories + ownedRooms,
    totalLabLevels,
    totalHeroSkillLevels,
    bestCoins,
    sRankCount,
    ssRankCount,
    aRankOrHigherCount,
    unlockedCount,
  };
}

